#!/usr/bin/env bash
# EXAMIS staging: apply Cloudflare's published address ranges. Installed as
# /usr/local/sbin/examis-cloudflare-ips (root) and run weekly by a timer.
#
# - Nginx takes the visitor's address from CF-Connecting-IP, only when the
#   connection comes from Cloudflare. Without this Laravel sees Cloudflare's
#   address, and students behind one edge share the sign-in rate limits.
# - The firewall opens 80/443 to Cloudflare only, so nobody bypasses it.
#
# A short or malformed answer from Cloudflare changes nothing.
set -euo pipefail

REALIP_CONF=/etc/nginx/conf.d/cloudflare-realip.conf
TAG=cloudflare

fail() { printf '[cloudflare-ips] ERROR: %s\n' "$*" >&2; exit 1; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

curl -fsS --retry 3 --max-time 20 https://www.cloudflare.com/ips-v4 -o "$tmp/v4"
curl -fsS --retry 3 --max-time 20 https://www.cloudflare.com/ips-v6 -o "$tmp/v6"

# Every non-empty line must be a CIDR range.
v4="$(grep -v '^[[:space:]]*$' "$tmp/v4" || true)"
v6="$(grep -v '^[[:space:]]*$' "$tmp/v6" || true)"
bad4="$(grep -cvE '^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$' <<<"$v4" || true)"
bad6="$(grep -cvE '^[0-9a-fA-F:]+/[0-9]{1,3}$' <<<"$v6" || true)"
[[ "$bad4" == "0" && "$bad6" == "0" ]] || fail "unexpected content in Cloudflare's lists"
[[ "$(wc -l <<<"$v4")" -ge 5 && "$(wc -l <<<"$v6")" -ge 3 ]] || fail "Cloudflare's lists look too short"

{
    echo "# Generated by examis-cloudflare-ips on $(date -u +%F). Do not edit."
    while read -r range; do echo "set_real_ip_from ${range};"; done <<<"$v4"
    while read -r range; do echo "set_real_ip_from ${range};"; done <<<"$v6"
    echo "real_ip_header CF-Connecting-IP;"
} > "$tmp/realip.conf"

install -m 644 "$tmp/realip.conf" "$REALIP_CONF"
if ! nginx -t 2>/dev/null; then
    rm -f "$REALIP_CONF"
    nginx -t
    fail "nginx rejected the configuration"
fi
systemctl reload nginx

# Replace the tagged web rules: delete from the highest number down so the
# numbering of the remaining rules does not shift.
ufw status numbered \
    | sed -n "s/^\[ *\([0-9]\+\)\].*# ${TAG}\$/\1/p" \
    | sort -rn \
    | while read -r number; do ufw --force delete "$number" >/dev/null; done
while read -r range; do
    ufw allow proto tcp from "$range" to any port 80,443 comment "$TAG" >/dev/null
done <<<"$(printf '%s\n%s\n' "$v4" "$v6")"
# Earlier open-to-all web rules, if any.
ufw delete allow 80/tcp >/dev/null 2>&1 || true
ufw delete allow 443/tcp >/dev/null 2>&1 || true

echo "[cloudflare-ips] $(wc -l <<<"$v4") IPv4 and $(wc -l <<<"$v6") IPv6 ranges applied"
